export function getProcessedBengaluruZones(): BengaluruZoneData[] {
  const zones = BASELINE_BENGALURU_ZONES.map((base) => {
    const riskEval = evaluateCompositeRisk({
      pm25: base.pm25,
      pm10: base.pm10,
      no2: base.no2,
      so2: base.so2,
      co: base.co,
      o3: base.o3,
      trafficDensity: base.trafficDensity,
      greenCoverPct: base.greenCoverPct,
      windSpeedKmh: base.windSpeedKmh,
      temperatureC: base.temperatureC,
    });

    return {
      ...base,
      compositeRiskScore: riskEval.compositeRiskScore,
      riskLevel: riskEval.riskLevel,
      dominantPollutant: riskEval.dominantPollutant,
      contributingFactors: riskEval.contributingFactors,
    } as BengaluruZoneData;
  });

  // Sort hotspots using manual Merge Sort
  return mergeSortByRisk(zones, 'compositeRiskScore', true) as BengaluruZoneData[];
}
